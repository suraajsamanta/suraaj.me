// Reproducible, dependency-free encoder for this one auditable SIMD128 kernel.
// Opcodes: https://webassembly.github.io/spec/core/binary/instructions.html
// Run: node src/app/madfun/beerio-2/build-road-simd.mjs
import { writeFileSync } from 'node:fs';
const u = n => { const a=[]; do { const b=n&127; n>>>=7; a.push(b|(n?128:0)); } while(n); return a; };
const str = s => [s.length,...Buffer.from(s)];
const section=(id,a)=>[id,...u(a.length),...a];
const signed = n => { const a=[]; let more=true; while(more) { const b=n&127; n>>=7; more=!((n===0 && !(b&64)) || (n===-1 && (b&64))); a.push(b|(more?128:0)); } return a; };
const get=i=>[0x20,i], set=i=>[0x21,i], icon=n=>[0x41,...signed(n)];
const fcon=n=>[0x44,...new Uint8Array(new Float64Array([n]).buffer)];
const sim=n=>[0xfd,...u(n)], splat=sim(0x14);
const add=sim(0xf0), sub=sim(0xf1), mul=sim(0xf2), min=sim(0xf4), max=sim(0xf5);
// Input blocks: ax[2], az[2], dx[2], dz[2], inverse-length-squared[2].
// nearest(ptr, blockCount, x, z) returns the winning packed lane index.
const load=offset=>[...get(0),...sim(0),4,...u(offset)];
const body=[3,2,0x7f,1,0x7c,6,0x7b,
 ...icon(0),...set(4),...icon(0),...set(5),...fcon(Infinity),...set(6),
 ...get(2),...splat,...set(7),...get(3),...splat,...set(8),
 0x02,0x40,0x03,0x40,
 ...get(4),...get(1),0x4f,0x0d,1,
 ...get(7),...load(0),...sub,...load(32),...mul,
 ...get(8),...load(16),...sub,...load(48),...mul,...add,...load(64),...mul,
 ...fcon(0),...splat,...max,...fcon(1),...splat,...min,...set(9),
 ...get(7),...load(0),...load(32),...get(9),...mul,...add,...sub,...set(10),
 ...get(8),...load(16),...load(48),...get(9),...mul,...add,...sub,...set(11),
 ...get(10),...get(10),...mul,...get(11),...get(11),...mul,...add,...set(12),
];
for(let lane=0;lane<2;lane++) body.push(
 ...get(12),...sim(0x21),lane,...get(6),0x63,0x04,0x40,
 ...get(12),...sim(0x21),lane,...set(6),
 ...get(4),...icon(2),0x6c,...icon(lane),0x6a,...set(5),0x0b);
body.push(...get(0),...icon(80),0x6a,...set(0),...get(4),...icon(1),0x6a,...set(4),0x0c,0,0x0b,0x0b,...get(5),0x0b);
const bytes=new Uint8Array([0,97,115,109,1,0,0,0,
 ...section(1,[1,0x60,4,0x7f,0x7f,0x7c,0x7c,1,0x7f]),
 ...section(2,[1,...str('env'),...str('memory'),2,0,1]),
 ...section(3,[1,0]),...section(7,[1,...str('nearest'),0,0]),
 ...section(10,[1,...u(body.length),...body])]);
new WebAssembly.Module(bytes);
writeFileSync(new URL('./road-simd-bytes.ts',import.meta.url),`// Generated by build-road-simd.mjs. Do not hand-edit.\nexport const ROAD_SIMD_BYTES = new Uint8Array([${[...bytes]}]);\n`);
console.log(`Generated ${bytes.length} bytes`);
