// Encrypts resume PDFs so they can live in this public repo.
// Usage: RESUME_KEY=<64 hex chars> node scripts/encrypt-resumes.mjs <ai-labs.pdf> <big-tech.pdf> <quant.pdf>
// Writes AES-256-GCM ciphertext (iv | tag | data, base64) to src/lib/resumes/*.ts.
import { createCipheriv, randomBytes } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const NAMES = ["ai-labs", "big-tech", "quant"];
const key = Buffer.from(process.env.RESUME_KEY ?? "", "hex");
const pdfs = process.argv.slice(2);

if (key.length !== 32) throw new Error("RESUME_KEY must be 64 hex characters");
if (pdfs.length !== NAMES.length) throw new Error(`Pass ${NAMES.length} PDFs: ${NAMES.join(", ")}`);

pdfs.forEach((pdf, i) => {
  const iv = randomBytes(12);
  const cipher = createCipheriv("aes-256-gcm", key, iv);
  const data = Buffer.concat([cipher.update(readFileSync(pdf)), cipher.final()]);
  const payload = Buffer.concat([iv, cipher.getAuthTag(), data]).toString("base64");
  const out = `src/lib/resumes/${NAMES[i]}.ts`;
  writeFileSync(out, `// Generated by scripts/encrypt-resumes.mjs. Encrypted; do not edit.\nconst payload = "${payload}";\n\nexport default payload;\n`);
  console.log(`${pdf} -> ${out}`);
});
